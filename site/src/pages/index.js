function Feature({ title, subtitle, paragraphs, figure, flipped }) {
	return (
		<Row className={styles.feature}>
			<Column size={4} order={flipped ? 2 : undefined}>
				<Stack gap="m">
					<h3>{title}</h3>
					<p>
						<b>{subtitle}</b>
					</p>
					<Stack gap="s">
						{paragraphs.map((para) => (
							<p key={para}>{para}</p>
						))}
					</Stack>
				</Stack>
			</Column>
			<Column size={8}>
				<div className={styles.featureFigure}>{figure}</div>
			</Column>
		</Row>
	);
}

